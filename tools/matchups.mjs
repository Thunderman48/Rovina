// Combat simulator for the AI's unit choice (like the combat simulators StarCraft bots use): for every
// pair of trainable squad types it fights equal-cost groups (about 100 resource a side) in an open arena,
// both sides played by the AI's own tactics, over several seeds, and writes the average outcome to
// js/ai/matchups.js. Score of A against B: A's share of HP left minus B's share, -1 .. 1.
// Run after changing unit stats or costs: node tools/matchups.mjs  (npm run matchups)
import { writeFileSync } from 'node:fs';
import { createGame, addSquad } from '../js/sim/state.js';
import { resolveRound } from '../js/sim/resolve.js';
import { aiOrders, aiMemory } from '../js/ai/ai.js';
import { FACTIONS, unitDef, trainCost } from '../js/data/units.js';

const SEEDS = 4, BUDGET = 100, ROUNDS = 20;
const roles = f => Object.keys(FACTIONS[f].units).filter(r => trainCost(f, r) > 0 && r !== 'builder' && !unitDef(f, r).summoned);
const each = (f, r) => trainCost(f, r) / (unitDef(f, r).pair || 1);

function duel(fa, ra, fb, rb, seed) {
  let s = createGame(seed, [fa, fb], 'greatfield');
  s.squads = []; s.buildings = []; s.terrain = []; s.revive = {};
  const H = s.board.h, W = s.board.w;
  const put = (p, f, r, x) => {
    const n = Math.max(1, Math.round(BUDGET / each(f, r)));
    for (let i = 0; i < n; i++) addSquad(s, p, r, x + (i % 3) * 2.6 * (p ? 1 : -1), H / 2 - 7 + Math.floor(i / 3) * 2.6);
  };
  put(0, fa, ra, W / 2 - 4.5); put(1, fb, rb, W / 2 + 4.5);   // inside engage range, so melee closes in
  const start = [0, 1].map(p => s.squads.filter(q => q.owner === p).reduce((n, q) => n + q.hp, 0));
  const mem = [aiMemory(), aiMemory()];
  for (let r = 0; r < ROUNDS; r++) {
    if ([0, 1].some(p => !s.squads.some(q => q.owner === p && q.hp > 0))) break;
    s = resolveRound(s, [aiOrders(s, 0, mem[0]), aiOrders(s, 1, mem[1])]).state;
  }
  const left = [0, 1].map(p => s.squads.filter(q => q.owner === p && q.hp > 0 && !q.ttl).reduce((n, q) => n + q.hp, 0) / start[p]);
  return Math.max(0, Math.min(1, left[0])) - Math.max(0, Math.min(1, left[1]));
}

const out = {};
for (const fa of Object.keys(FACTIONS)) for (const fb of Object.keys(FACTIONS)) {
  const key = fa + '>' + fb;
  out[key] = {};
  for (const ra of roles(fa)) {
    out[key][ra] = {};
    for (const rb of roles(fb)) {
      // reuse the mirrored result when it was already fought
      const back = out[fb + '>' + fa]?.[rb]?.[ra];
      if (back !== undefined) { out[key][ra][rb] = -back; continue; }
      let sum = 0;
      for (let seed = 1; seed <= SEEDS; seed++) sum += seed % 2 ? duel(fa, ra, fb, rb, seed) : -duel(fb, rb, fa, ra, seed);
      out[key][ra][rb] = Math.round(sum / SEEDS * 100) / 100;
      process.stdout.write(`${key} ${ra} vs ${rb}: ${out[key][ra][rb]}\n`);
    }
  }
}
writeFileSync(new URL('../js/ai/matchups.js', import.meta.url),
  '// Generated by tools/matchups.mjs (equal-cost duels in an open arena, AI tactics on both sides). Do not edit.\n' +
  '// MATCHUPS["attackerFaction>defenderFaction"][attackerRole][defenderRole] = score -1 .. 1 (1: wins with no losses)\n' +
  'export const MATCHUPS = ' + JSON.stringify(out, null, 1).replace(/\n\s+(?=[-\d"}])/g, ' ') + ';\n');
console.log('wrote js/ai/matchups.js');
